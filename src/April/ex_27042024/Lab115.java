package April.ex_27042024;

public class Lab115 {
    public static void main(String[] args) {
        //while
        // A -> Initialisation
        // B -> Condition
        //C -> Increment/Decrement
        int i =1;
        while (i<=10){
            //Execute the Code
            System.out.println(i);
            i++; //C

            //i -> 1-10, print 1 to 10
        }

        for (int j = 1; j <= 10 ; j++) {
            System.out.println(j);
        }

    }
}
